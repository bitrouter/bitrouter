//! Real write-only native worker, command permission cards and Cargo effects.
use super::*;
use bitrouter_orchestrator::goal::decision::{PermissionDecision, PermissionState};

pub(super) const BUILD_SCRIPT: &str = r#"fn main() -> std::io::Result<()> {
    use std::io::Write;
    std::fs::OpenOptions::new().create(true).append(true).open("../outside-marker")?.write_all(b"x")?;
    Ok(())
}
"#;

async fn setup() -> Result<Fixture> {
    // The single-connection database also exercises concurrent permission
    // admission and control monitoring without hiding pool starvation.
    let setup = Setup::new_without_external_harnesses().await?;
    tokio::fs::create_dir(setup.workspace.join("src")).await?;
    tokio::fs::write(setup.workspace.join("Cargo.toml"), "[package]\nname = \"goal-check-fixture\"\nversion = \"0.0.0\"\nedition = \"2024\"\n[workspace]\n").await?;
    tokio::fs::write(
        setup.workspace.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"goal-check-fixture\"\nversion = \"0.0.0\"\n",
    )
    .await?;
    tokio::fs::write(setup.workspace.join(".gitignore"), "/target\n").await?;
    tokio::fs::write(
        setup.workspace.join("src/lib.rs"),
        "// Cargo-built command permission fixture.\n",
    )
    .await?;
    Mock::given(method("POST"))
        .and(path("/v1/chat/completions"))
        .respond_with(native::model)
        .with_priority(1)
        .mount(&setup.backend)
        .await;
    setup.start().await
}

async fn pending(fixture: &Fixture, id: &str) -> Result<PermissionDecision> {
    let goal = wait_for(&fixture.socket, id, |goal| {
        goal.workflow
            .decisions
            .iter()
            .any(|decision| decision.check.is_some() && decision.state == PermissionState::Pending)
    })
    .await?;
    goal.workflow
        .decisions
        .into_iter()
        .find(|decision| decision.check.is_some() && decision.state == PermissionState::Pending)
        .context("check permission missing")
}

async fn respond(
    fixture: &Fixture,
    id: &str,
    decision: &PermissionDecision,
    option: &str,
) -> Result<()> {
    rpc(
        &fixture.socket,
        GoalCommand::RespondDecision {
            operation_id: format!("reply-{}", decision.id),
            goal_id: id.into(),
            decision_id: decision.id.clone(),
            expected_requirements_revision: decision.requirements_revision,
            option_id: option.into(),
        },
    )
    .await?;
    Ok(())
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn command_checks_wait_for_exact_approval_at_task_and_delivery() -> Result<()> {
    let fixture = setup().await?;
    let result = async {
        let id = fixture.create_with("NATIVE_COMMAND_CHECK_FIXTURE: write the fixture build script and verify the task and integrated delivery with Cargo tests.").await?;
        let first = pending(&fixture, &id).await?;
        let marker = fixture.root(&id).parent().context("artifact parent missing")?.join("outside-marker");
        tokio::time::sleep(Duration::from_millis(250)).await;
        assert!(!tokio::fs::try_exists(&marker).await?);
        let scope = first.check.as_ref().context("permission scope missing")?;
        assert_eq!(tokio::fs::read_to_string(scope.workspace.join("build.rs")).await?, BUILD_SCRIPT);
        let material = crate::goal_artifacts::read(&fixture.root(&id), &first.request).await?;
        assert_eq!(crate::goal_permission_material::decision_value(&material, &first)?["command"], "cargo test --all-features");
        respond(&fixture, &id, &first, "allow-once").await?;
        let second = pending(&fixture, &id).await?;
        assert_ne!(first.id, second.id);
        assert_eq!(second.check.as_ref().map(|check| check.specification.id.as_str()), Some("operation-final"));
        assert_eq!(tokio::fs::read(&marker).await?, b"x");
        respond(&fixture, &id, &second, "allow-once").await?;
        let completed = wait_for(&fixture.socket, &id, |goal| goal.workflow.completion.completed_for(1)).await?;
        assert_eq!(tokio::fs::read(&marker).await?, b"xx");
        assert!(completed.workflow.tasks[0].executions.last().is_some_and(|execution| execution.handoff.is_some()));
        Ok(())
    }.await;
    fixture.finish(result).await
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn command_checks_reject_denial_pause_and_changed_artifacts() -> Result<()> {
    for action in ["deny", "pause", "edit"] {
        let fixture = setup().await?;
        let result = async {
            let id = fixture.create_with("NATIVE_COMMAND_CHECK_FIXTURE: write the fixture build script and verify the task and integrated delivery with Cargo tests.").await?;
            let decision = pending(&fixture, &id).await?;
            let marker = fixture.root(&id).parent().context("artifact parent missing")?.join("outside-marker");
            match action {
                "deny" => respond(&fixture, &id, &decision, "deny-once").await?,
                "pause" => control(&fixture.socket, &id, "pause-check", RunIntent::Pause).await?,
                "edit" => {
                    let scope = decision.check.as_ref().context("check scope missing")?;
                    tokio::fs::write(scope.workspace.join("src/lib.rs"), "// Changed after permission admission.\n").await?;
                    respond(&fixture, &id, &decision, "allow-once").await?;
                }
                _ => anyhow::bail!("unknown fixture action"),
            }
            let settled = wait_for(&fixture.socket, &id, |goal| goal.workflow.tasks.iter().flat_map(|task| &task.executions)
                .flat_map(|execution| &execution.checks).any(|check| matches!(check.state,
                    bitrouter_orchestrator::goal::workflow::CheckState::Observed { passed: false, .. }))).await?;
            assert!(!tokio::fs::try_exists(&marker).await?, "{action}");
            assert!(!settled.workflow.completion.completed_for(1));
            Ok(())
        }.await;
        fixture.finish(result).await?;
    }
    Ok(())
}
