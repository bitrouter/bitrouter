//! Explicit shared-gateway submission and durable status lookup.
//!
//! The `submit_*` methods require shared execution metadata. A local gateway can
//! execute a request before this requirement fails; these calls never probe,
//! retry or fall back to another interface. Existing model methods support local
//! gateways. A 202 observes prior work, including terminal work, without replaying
//! model output or resuming a stream. Preserve request semantics and all effective
//! semantic headers when explicitly resubmitting an idempotency key.

pub(crate) mod media_type;
mod options;
mod response;

use std::fmt;

use bitrouter_ai::{
    decisions::DecisionRequest,
    gateway::execution::GatewayExecution,
    protocol::{
        chat_completions::{ChatChunk, ChatRequest, ChatResponse},
        decisions::DecisionsResponse,
        messages::{MessagesEvent, MessagesRequest, MessagesResponse},
        responses::{ResponsesEvent, ResponsesRequest, ResponsesResponse},
    },
    types::ModelOperation,
};
use reqwest::{Response, StatusCode, header::HeaderMap};
use serde::{Serialize, de::DeserializeOwned};

use super::GatewayClient;
use crate::{
    error::{Error, Result},
    stream::{EventStream, Protocol},
    transport,
};
use response::Evidence;

/// Per-submission identity and semantic headers, validated on every call.
#[derive(Clone, Default)]
pub struct SubmissionOptions {
    /// Optional caller correlation, normalized to 1..256 textual bytes.
    pub correlation_id: Option<String>,
    /// Optional tenant/principal-scoped binding. Never generated by the SDK.
    pub idempotency_key: Option<String>,
    /// Only the fixed gateway v1 semantic header set is accepted. Duplicate
    /// value order and empty values are preserved. Authentication and profile
    /// selection are not configurable here.
    pub headers: HeaderMap,
}

impl fmt::Debug for SubmissionOptions {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("SubmissionOptions").finish_non_exhaustive()
    }
}

/// Validated response identity, available before a stream is consumed.
#[derive(Clone, PartialEq, Eq)]
pub struct ExecutionMetadata {
    /// Service identity, distinct from provider IDs and continuation handles.
    pub execution_id: String,
    /// Correlation of this HTTP request, possibly different from the original.
    pub correlation_id: String,
    /// Canonical absolute query URL built from the configured origin/prefix.
    /// This is not the raw Location header and is never followed automatically.
    pub status_location: String,
}

impl fmt::Debug for ExecutionMetadata {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("ExecutionMetadata").finish_non_exhaustive()
    }
}

/// First-submission output or a status projection of previously accepted work.
pub enum Submission<T> {
    /// Ordinary JSON output or an incremental stream, with its durable identity.
    Response {
        response: T,
        metadata: ExecutionMetadata,
    },
    /// No model output is replayed. Boxing bounds the status variant's size.
    Existing {
        execution: Box<GatewayExecution>,
        metadata: ExecutionMetadata,
    },
}

impl<T> fmt::Debug for Submission<T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct(match self {
            Self::Response { .. } => "Submission::Response",
            Self::Existing { .. } => "Submission::Existing",
        })
        .finish_non_exhaustive()
    }
}

impl GatewayClient {
    /// Submit ordinary Chat Completions to a shared gateway without replay.
    pub async fn submit_chat_completions(
        &self,
        request: &ChatRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<ChatResponse>> {
        options::stream(request.stream, false, &request.extra)?;
        self.submit_json(
            "v1/chat/completions",
            request,
            options,
            ModelOperation::Generation,
        )
        .await
    }

    /// Submit ordinary Messages to a shared gateway without replay.
    pub async fn submit_messages(
        &self,
        request: &MessagesRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<MessagesResponse>> {
        options::stream(request.stream, false, &request.extra)?;
        self.submit_json("v1/messages", request, options, ModelOperation::Generation)
            .await
    }

    /// Submit ordinary Responses; managed-profile selectors are rejected locally.
    pub async fn submit_responses(
        &self,
        request: &ResponsesRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<ResponsesResponse>> {
        options::stream(request.stream, false, &request.extra)?;
        options::ordinary_responses(request)?;
        self.submit_json("v1/responses", request, options, ModelOperation::Generation)
            .await
    }

    /// Submit a nonstreaming Decisions request to a shared gateway.
    pub async fn submit_decisions(
        &self,
        request: &DecisionRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<DecisionsResponse>> {
        self.submit_json("v1/decisions", request, options, ModelOperation::Decisions)
            .await
    }

    /// Open a shared Chat stream or observe an existing execution.
    pub async fn submit_stream_chat_completions(
        &self,
        request: &ChatRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<EventStream<ChatChunk>>> {
        options::stream(request.stream, true, &request.extra)?;
        self.submit_events("v1/chat/completions", request, options, Protocol::Chat)
            .await
    }

    /// Open a shared Messages stream or observe an existing execution.
    pub async fn submit_stream_messages(
        &self,
        request: &MessagesRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<EventStream<MessagesEvent>>> {
        options::stream(request.stream, true, &request.extra)?;
        self.submit_events("v1/messages", request, options, Protocol::Messages)
            .await
    }

    /// Open an ordinary shared Responses stream; never select managed execution.
    pub async fn submit_stream_responses(
        &self,
        request: &ResponsesRequest,
        options: &SubmissionOptions,
    ) -> Result<Submission<EventStream<ResponsesEvent>>> {
        options::stream(request.stream, true, &request.extra)?;
        options::ordinary_responses(request)?;
        self.submit_events("v1/responses", request, options, Protocol::Responses)
            .await
    }

    /// Explicitly query a tenant-authorized execution on the configured service.
    /// A candidate ID from a 503 can return 404; it does not prove acceptance.
    pub async fn execution(&self, id: &str) -> Result<GatewayExecution> {
        let response = self
            .http
            .get(response::resource(self, id)?)
            .send()
            .await
            .map_err(Error::transport)?;
        let response = transport::successful(response, self.options.max_response_bytes).await?;
        let evidence = Evidence::new(&response);
        let result = async {
            if response.status() != StatusCode::OK {
                return Err(Error::Response("execution query requires HTTP 200"));
            }
            let metadata = response::metadata(self, response.headers(), None)?;
            let execution: GatewayExecution =
                response::json(response, self.options.max_response_bytes).await?;
            if execution.execution_id != id
                || metadata.execution_id != id
                || execution.correlation_id != metadata.correlation_id
            {
                return Err(Error::Response("execution query identity mismatch"));
            }
            Ok(execution)
        }
        .await;
        result.map_err(|error| evidence.failure(error))
    }

    async fn submit_json<T: DeserializeOwned>(
        &self,
        path: &str,
        request: &impl Serialize,
        options: &SubmissionOptions,
        operation: ModelOperation,
    ) -> Result<Submission<T>> {
        match self
            .submit_raw(path, request, options, operation, false)
            .await?
        {
            Submission::Existing {
                execution,
                metadata,
            } => Ok(Submission::Existing {
                execution,
                metadata,
            }),
            Submission::Response { response, metadata } => {
                let evidence = Evidence::new(&response);
                let response = response::json(response, self.options.max_response_bytes)
                    .await
                    .map_err(|error| evidence.failure(error))?;
                Ok(Submission::Response { response, metadata })
            }
        }
    }

    async fn submit_events<T: DeserializeOwned + Send + 'static>(
        &self,
        path: &str,
        request: &impl Serialize,
        options: &SubmissionOptions,
        protocol: Protocol,
    ) -> Result<Submission<EventStream<T>>> {
        match self
            .submit_raw(path, request, options, ModelOperation::Generation, true)
            .await?
        {
            Submission::Existing {
                execution,
                metadata,
            } => Ok(Submission::Existing {
                execution,
                metadata,
            }),
            Submission::Response { response, metadata } => Ok(Submission::Response {
                response: crate::stream::decode(response, self.options.max_event_bytes, protocol),
                metadata,
            }),
        }
    }

    async fn submit_raw(
        &self,
        path: &str,
        request: &impl Serialize,
        options: &SubmissionOptions,
        operation: ModelOperation,
        stream: bool,
    ) -> Result<Submission<Response>> {
        let headers = options::headers(options)?;
        let correlation = headers
            .get("x-bitrouter-request-id")
            .and_then(|value| value.to_str().ok());
        let response = self
            .http
            .post(self.url(path)?)
            // reqwest replaces each header's values, retaining duplicate order.
            // https://docs.rs/reqwest/latest/reqwest/struct.RequestBuilder.html#method.headers
            .headers(headers.clone())
            .header(
                reqwest::header::ACCEPT,
                if stream {
                    "text/event-stream"
                } else {
                    "application/json"
                },
            )
            .json(request)
            .send()
            .await
            .map_err(Error::transport)?;
        let response = transport::successful(response, self.options.max_response_bytes).await?;
        let evidence = Evidence::new(&response);
        let result = async {
            if !matches!(response.status(), StatusCode::OK | StatusCode::ACCEPTED) {
                return Err(Error::Response("submission requires HTTP 200 or 202"));
            }
            let metadata = response::metadata(self, response.headers(), correlation)?;
            if response.status() == StatusCode::ACCEPTED {
                let execution: GatewayExecution =
                    response::json(response, self.options.max_response_bytes).await?;
                if execution.execution_id != metadata.execution_id
                    || execution.operation != operation
                    || !options::normalized_identity(&execution.correlation_id)
                {
                    return Err(Error::Response(
                        "invalid existing execution identity or operation",
                    ));
                }
                // The DTO retains the original correlation; the header echoes
                // this submission's correlation, which may legitimately differ.
                Ok(Submission::Existing {
                    execution: Box::new(execution),
                    metadata,
                })
            } else {
                response::content_type(
                    response.headers(),
                    if stream {
                        "text/event-stream"
                    } else {
                        "application/json"
                    },
                )?;
                Ok(Submission::Response { response, metadata })
            }
        }
        .await;
        result.map_err(|error| evidence.failure(error))
    }
}

pub(super) fn reject_existing(response: Response) -> Result<Response> {
    if response.status() == StatusCode::ACCEPTED {
        return Err(Evidence::new(&response).failure(Error::Response(
            "existing execution requires submit_* or execution(id); no model output was replayed",
        )));
    }
    Ok(response)
}
