import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const [source,id]=process.argv.slice(2),archive='/Users/kelsen/.codex/archives/bro-refactor/2026-10-16';
if(!source?.startsWith('/var/folders/')||!/^native-history-[a-z0-9-]+-fixture$/.test(id))throw Error('invalid fixture scope');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const walk=root=>fs.readdirSync(root,{withFileTypes:true}).flatMap(entry=>entry.isDirectory()?walk(path.join(root,entry.name)):[path.join(root,entry.name)]);
const snapshot=root=>Object.fromEntries(walk(root).sort().map(file=>{const stat=fs.lstatSync(file);if(!stat.isFile())throw Error('non-regular entry');return[path.relative(root,file),{sha256:sha(fs.readFileSync(file)),bytes:stat.size,mode:stat.mode&0o777}]}));
const before=snapshot(source),tar=`${archive}/${id}.tar.gz`;
if(fs.existsSync(tar))throw Error('archive already exists');
execFileSync('tar',['-czf',tar,'-C',source,'.']);
const restored=fs.mkdtempSync(`/tmp/${id}-audit-`);
execFileSync('tar',['-xzf',tar,'-C',restored]);
for(const candidate of[snapshot(restored),snapshot(source)])if(JSON.stringify(candidate)!==JSON.stringify(before))throw Error('fixture drift or extraction mismatch');
const result={source,restored,files:before,verifiedFiles:Object.keys(before).length,tarSha256:sha(fs.readFileSync(tar)),scope:'Failed-test filesystem and SQLite only. Not a process image, private ACP state or abrupt-crash recovery proof.'};
fs.writeFileSync(`${archive}/${id}-audit.json`,JSON.stringify(result,null,2)+'\n',{flag:'wx'});
fs.copyFileSync('/tmp/bro-native-history-fixture-archive1.mjs',`${archive}/${id}-runner.mjs`);
console.log(JSON.stringify({verifiedFiles:result.verifiedFiles,tarSha256:result.tarSha256,restored}));
